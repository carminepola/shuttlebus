async function run() {
  const client = new MongoClient(connectionString!);
  await client.connect();
  const col = client.db().collection("lng");

  let inserted = 0;
  for (const [txt, values] of Object.entries(KEYS)) {
    if (dryRun) {
      const exists = await col.countDocuments({ txt }, { limit: 1 });
      if (!exists) {
        console.log(`[dry-run] da inserire: ${txt}`);
        inserted++;
      }
      continue;
    }
    const r = await col.updateOne({ txt }, { $setOnInsert: { txt, ...values } }, { upsert: true });
    if (r.upsertedCount > 0) {
      console.log(`+ ${txt}`);
      inserted++;
    }
  }
  console.log(`${dryRun ? "Da inserire" : "Inserite"}: ${inserted} / ${Object.keys(KEYS).length} chiavi`);
  await client.close();
}

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
